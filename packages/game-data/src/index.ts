export function createUnits(owner: Player, armyId: string): Unit[] {
  const army = armies.find((a) => a.id === armyId);
  if (!army) throw Error("Unknown training army");
  return Array.from({ length: 2 }, (_, i) => {
    const id = `p${owner}-u${i}`;
    const { wounds, ...profile } = structuredClone(army);
    return {
      ...profile,
      id,
      name: `${army.name} ${i + 1}`,
      owner,
      points: 100,
      keywords: ["INFANTRY", "GRENADES", "SMOKE"],
      startingStrength: 3,
      shocked: false,
      movedDistance: 0,
      shotTurn: -1,
      charged: false,
      fought: false,
      piled: false,
      consolidated: false,
      oneShotUsed: [],
      models: Array.from({ length: 3 }, (_, j) => ({
        id: `${id}-m${j}`,
        x: owner === 0 ? 4 : 40,
        y: 8 + i * 14 + j * 1.5,
        radius: 16 / 25.4,
        wounds,
        maxWounds: wounds,
      })),
    };
  });
}
